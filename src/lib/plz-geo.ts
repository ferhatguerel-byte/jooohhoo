function toRad(deg: number): number {
  return (deg * Math.PI) / 180
}

function haversineKm(a: [number, number], b: [number, number]): number {
  const R = 6371
  const dLat = toRad(b[0] - a[0])
  const dLon = toRad(b[1] - a[1])
  const lat1 = toRad(a[0])
  const lat2 = toRad(b[0])
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(lat1) * Math.cos(lat2) * Math.sin(dLon / 2) ** 2
  return 2 * R * Math.asin(Math.sqrt(h))
}

/** Gibt die ungefähre Entfernung in km zwischen zwei PLZ zurück, oder null wenn unbekannt. */
export function estimatePlzDistanceKm(plzA: string, plzB: string): number | null {
  const zoneA = PLZ_ZONE_CENTERS[plzA.slice(0, 2)]
  const zoneB = PLZ_ZONE_CENTERS[plzB.slice(0, 2)]
  if (!zoneA || !zoneB) return null
  if (plzA.slice(0, 2) === plzB.slice(0, 2)) return 0
  return Math.round(haversineKm(zoneA, zoneB))
}

